x64 <- function(code) with_jax_config("jax_enable_x64", TRUE, code)
rosen <- function(x) {
  n <- length(x)
  a <- x[sl(1L, NULL)]
  b <- x[sl(NULL, -1L)]
  jnp_sum(100.0 * (a - b^2L)^2L + (1 - b)^2L)
}
lbfgs <- "l-bfgs-experimental-do-not-rely-on-this"

test_that("BFGS matches the wheel on the Rosenbrock function", {
  skip_if_no_backend()
  x64({
    r <- scipy_optimize_minimize(rosen, fx$x0, method = "BFGS")
    expect_named(r, c("x", "success", "status", "fun", "jac", "hess_inv", "nfev", "njev", "nit"))
    expect_jax_equal(r$x, fx$bfgs_x, tolerance = 1e-8)
    expect_jax_equal(r$fun, fx$bfgs_fun, tolerance = 1e-8)
    expect_jax_equal(r$hess_inv, fx$bfgs_hess_inv, tolerance = 1e-6)
    expect_jax_equal(r$nit, fx$bfgs_nit, dtype = "int64")
    expect_jax_equal(r$nfev, fx$bfgs_nfev)
    expect_jax_equal(r$njev, fx$bfgs_njev)
    expect_jax_equal(r$status, fx$bfgs_status, dtype = "int64")
    expect_jax_equal(r$success, fx$bfgs_success, dtype = "bool")
    expect_identical(dtype(r$x), "float64")
    r <- scipy_optimize_minimize(rosen, fx$x0, method = "bfgs",
                                 options = list(maxiter = 5L, gtol = 1e-3))
    expect_jax_equal(r$x, fx$bfgs_max_x, tolerance = 1e-10)
    expect_jax_equal(r$status, fx$bfgs_max_status)
    expect_jax_equal(r$nit, fx$bfgs_max_nit)
    r <- jit(function(x0) scipy_optimize_minimize(rosen, x0, method = "BFGS"))(fx$x0)
    expect_jax_equal(r$x, fx$bfgs_x, tolerance = 1e-8)
    expect_jax_equal(r$nit, fx$bfgs_nit)
  })
})

