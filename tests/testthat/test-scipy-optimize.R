test_that("minimize passes extra arguments and maps over starting points", {
  skip_if_no_backend()
  Q <- matrix(c(3, 0.5, 0.5, 1), 2)
  quad <- function(x, Q, c) 0.5 * jnp_dot(x, jnp_dot(Q, x)) - jnp_dot(c, x)
  x64({
    r <- scipy_optimize_minimize(quad, c(0, 0), args = list(Q, c(1, -2)), method = "BFGS")
    expect_jax_equal(r$x, fx$quad_x, tolerance = 1e-10)
    expect_jax_equal(r$x, solve(Q, c(1, -2)), tolerance = 1e-6)
    expect_jax_equal(r$nit, fx$quad_nit)
    xs <- as.array(vmap(function(x0) scipy_optimize_minimize(quad, x0, args = list(Q, c(1, -2)),
                                                             method = "BFGS")$x)(rbind(c(0, 0), c(1, 1))))
    expect_equal(xs[1L, ], fx$quad_x, tolerance = 1e-12)
    expect_equal(xs[2L, ], solve(Q, c(1, -2)), tolerance = 1e-4)
  })
  r <- scipy_optimize_minimize(function(x) jnp_sum((x - c(1, 2))^2), c(0, 0), method = "BFGS")
  expect_identical(dtype(r$x), "float32")
  expect_jax_equal(r$x, c(1, 2), tolerance = 1e-5)
  expect_error(scipy_optimize_minimize(rosen, c(0, 0), method = "Nelder-Mead"),
               "Method Nelder-Mead not recognized")
  expect_error(scipy_optimize_minimize(rosen, c(0, 0), args = 1, method = "BFGS"),
               "must be a tuple")
})

test_that("float32 minimization (x64 disabled) matches the wheel", {
  skip_if_no_backend()
  r <- scipy_optimize_minimize(rosen, fx$x0, method = "BFGS")
  expect_identical(dtype(r$x), "float32")
  expect_identical(dtype(r$nit), "int32")
  expect_identical(dtype(r$success), "bool")
  # A float32 line search near the minimum is decided by the last bits, so the path
  # depends on how the platform rounds: the iterate moves by up to 1e-2 and the counts
  # change. The counts of JAX are matched within a factor of two.
  near <- function(got, want) {
    g <- as.numeric(as.array(got))
    expect_true(g > want / 2 && g < 2 * want, info = paste("got", g, "want", want))
  }
  expect_jax_equal(r$x, fx$bfgs32_x, tolerance = 1e-4)
  expect_jax_equal(r$fun, fx$bfgs32_fun, tolerance = 1e-4)
  near(r$nit, fx$bfgs32_nit)
  near(r$nfev, fx$bfgs32_nfev)
  expect_jax_equal(r$status, fx$bfgs32_status)
  r <- scipy_optimize_minimize(rosen, fx$x0, method = lbfgs)
  expect_jax_equal(r$x, fx$lbfgs32_x, tolerance = 1e-2)
  expect_jax_equal(r$fun, fx$lbfgs32_fun, tolerance = 1e-4)
  near(r$nit, fx$lbfgs32_nit)
  near(r$nfev, fx$lbfgs32_nfev)
  expect_jax_equal(r$status, fx$lbfgs32_status)
})

test_that("line_search matches the wheel", {
  skip_if_no_backend()
  x64({
    xk <- as_jax(fx$x0)
    pk <- -grad(rosen)(xk)
    ls <- scipy_optimize_line_search(rosen, xk, pk)
    expect_jax_equal(ls$a_k, fx$ls_a_k, tolerance = 1e-10)
    expect_jax_equal(ls$f_k, fx$ls_f_k, tolerance = 1e-10)
    expect_jax_equal(ls$g_k, fx$ls_g_k, tolerance = 1e-10)
    expect_jax_equal(ls$nfev, fx$ls_nfev)
    expect_jax_equal(ls$ngev, fx$ls_ngev)
    expect_jax_equal(ls$nit, fx$ls_nit)
    expect_jax_equal(ls$k, fx$ls_k)
    expect_jax_equal(ls$status, fx$ls_status)
    expect_jax_equal(ls$failed, fx$ls_failed)
    ls <- scipy_optimize_line_search(rosen, xk, pk, old_fval = rosen(xk),
                                     old_old_fval = rosen(xk) + 10, gfk = -pk, c2 = 0.1)
    expect_jax_equal(ls$a_k, fx$ls2_a_k, tolerance = 1e-10)
    expect_jax_equal(ls$f_k, fx$ls2_f_k, tolerance = 1e-10)
    expect_jax_equal(ls$nfev, fx$ls2_nfev)
    expect_jax_equal(ls$status, fx$ls2_status)
  })
})

