# jax.stages: Traced, Lowered and Compiled stages of jit functions.

test_that("jit functions expose the trace, lower and compile stages", {
  skip_if_no_backend()
  f <- jit(function(x, y) list(s = jnp_sum(x * y), d = x - y))
  x <- as_jax(c(1, 2, 3))
  y <- as_jax(c(4, 5, 6))
  tr <- f$trace(x, y)
  expect_s3_class(tr, "jax_stages_traced")
  expect_s3_class(tr$jaxpr, "jax_closed_jaxpr")
  expect_identical(tr$out_info$s$shape, integer(0))
  expect_identical(tr$out_info$d$dtype, "float32")
  expect_identical(tr$args_info[[1L]]$shape, 3L)
  expect_identical(length(tr$in_avals), 2L)
  expect_jax_equal(tr(x, y)$s, 32)
  lo <- tr$lower()
  expect_s3_class(lo, "jax_stages_lowered")
  expect_match(lo$as_text(), "stablehlo.multiply", fixed = TRUE)
  expect_identical(lo$as_text(), f$lower(x, y)$as_text())
  expect_identical(lo$as_text(dialect = "stablehlo"), lo$compiler_ir())
  expect_error(lo$as_text(dialect = "tosa"), class = "jax_value_error")
  expect_null(lo$cost_analysis())
  co <- lo$compile()
  expect_s3_class(co, "jax_stages_compiled")
  r <- co(x, y)
  expect_named(r, c("s", "d"))
  expect_jax_equal(r$s, 32)
  expect_jax_equal(r$d, c(-3, -3, -3))
  expect_jax_equal(co$call(y, x)$d, c(3, 3, 3))
  expect_identical(co$out_info$d$shape, 3L)
  expect_null(co$memory_analysis())
  expect_false(is.null(co$runtime_executable()))
  expect_error(co(as_jax(c(1, 2)), y), "Argument types differ", class = "jax_type_error")
  expect_error(co(as_jax(1:3), y), "Argument types differ", class = "jax_type_error")
  expect_error(co(x), "different input pytree", class = "jax_type_error")
  expect_error(vmap(co)(jnp_stack(list(x, x)), jnp_stack(list(y, y))),
               "Cannot apply JAX transformations", class = "jax_type_error")
  expect_error(co$nope, class = "jax_attribute_error")
  expect_error(f$nope, class = "jax_attribute_error")
  expect_output(print(co), "Compiled stage of a jit function; arguments: f32[3], f32[3]",
                fixed = TRUE)
})

test_that("stages handle abstract arguments, static arguments and the cache", {
  skip_if_no_backend()
  x <- as_jax(c(1, 2, 3))
  g <- jit(function(x, n) x * n, static_argnums = 1L)
  cg <- g$lower(x, 3)$compile()
  expect_jax_equal(cg(x), c(3, 6, 9))
  expect_identical(g$eval_shape(x, 3)$shape, 3L)
  # lowering needs shapes and dtypes only
  h <- jit(function(m) jnp_sum(m, axis = 0L))
  lo <- h$lower(ShapeDtypeStruct(c(2L, 3L), "float32"))
  expect_identical(lo$out_info$shape, 3L)
  expect_jax_equal(lo$compile()(jnp_ones(c(2L, 3L))), c(2, 2, 2))
  # clear_cache makes the next call trace again
  n <- 0L
  k <- jit(function(x) { n <<- n + 1L; x + 1 })
  k(x); k(x)
  expect_identical(n, 1L)
  k$clear_cache()
  k(x)
  expect_identical(n, 2L)
})
